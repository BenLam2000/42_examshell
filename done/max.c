int	max(int* tab, unsigned int len)
{
	int	max;

	if (len == 0)
		return (0);

	max = tab[0];
	tab++;
	len--;
	while (len > 0)
	{
		if (*tab > max)
			max = *tab;
		tab++;
		len--;
	}
	return (max);
}
